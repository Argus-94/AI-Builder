import { utf8ToBase64 } from "./base64.ts";

export type ProjectBuildRunnerOptions = Readonly<{
  projectRoot: string;
  projectName: string;
  projectKind: string;
  backend: "termux" | "ubuntu-proot";
  variant: string;
  buildSubdirectory?: string;
  command: string;
  sharedRoot?: string;
}>;

const DEFAULT_SHARED_ROOT = "/storage/emulated/0/AIBuilderTermux";
export const PROJECT_BUILD_RUNNER_MARKER = "# AI_BUILDER_PROJECT_BUILD_RUNNER:v1";

function shellQuote(value: string): string {
  if (/[\0\r\n]/.test(value)) throw new Error("PROJECT_BUILD_RUNNER_VALUE_INVALID");
  return `'${value.replace(/'/g, `'\\''`)}'`;
}

export function projectBuildRunnerSlug(value: string): string {
  const slug = String(value || "project")
    .normalize("NFKD")
    .replace(/[\u0300-\u036f]/g, "")
    .toLowerCase()
    .replace(/[^a-z0-9_-]+/g, "-")
    .replace(/^-+|-+$/g, "")
    .slice(0, 40);
  return slug || "project";
}

function safeComment(value: string): string {
  return String(value || "unknown").replace(/[^a-zA-Z0-9_.:+-]/g, "_").slice(0, 80) || "unknown";
}

/**
 * Build the project-visible runner body. The passed command is generated by the
 * selected build adapter, not copied from project-controlled shell files.
 */
export function buildProjectBuildRunnerContent(options: ProjectBuildRunnerOptions): string {
  const command = String(options.command || "").trim();
  if (!command || /\0/.test(command)) throw new Error("PROJECT_BUILD_RUNNER_COMMAND_INVALID");
  const buildSubdirectory = String(options.buildSubdirectory || ".").replace(/\\/g, "/");
  if (buildSubdirectory !== "." && (buildSubdirectory.startsWith("/") || buildSubdirectory.split("/").some((part) => part === ".." || part === "." || part === ""))) {
    throw new Error("PROJECT_BUILD_RUNNER_BUILD_ROOT_INVALID");
  }
  const sharedRoot = shellQuote(options.sharedRoot || DEFAULT_SHARED_ROOT);
  const audit = [
    "settings.gradle", "settings.gradle.kts", "build.gradle", "build.gradle.kts",
    "gradle.properties", "gradle/wrapper/gradle-wrapper.properties", "gradle/wrapper/gradle-wrapper.jar",
    "package.json", "pnpm-lock.yaml", "package-lock.json", "yarn.lock", "bun.lockb",
    "pubspec.yaml", "pubspec.lock", "pom.xml", "CMakeLists.txt", "Android.mk",
    "capacitor.config.ts", "capacitor.config.js", "capacitor.config.json", "config.xml",
  ];
  return [
    "#!/usr/bin/env bash",
    PROJECT_BUILD_RUNNER_MARKER,
    `# Backend: ${safeComment(options.backend)}; project kind: ${safeComment(options.projectKind)}; variant: ${safeComment(options.variant)}`,
    "# Generated by AI Builder. Project build configuration and lockfiles are inspected, not rewritten by this runner.",
    "set +e",
    'AIB_PROJECT_ROOT="$(CDPATH= cd -- "$(dirname -- "${BASH_SOURCE[0]}")" 2>/dev/null && pwd -P)" || { echo AIB_PROJECT_ROOT_INVALID >&2; exit 64; }',
    '[ -d "$AIB_PROJECT_ROOT" ] && [ ! -L "$AIB_PROJECT_ROOT" ] || { echo AIB_PROJECT_ROOT_INVALID >&2; exit 64; }',
    `AIB_ALLOWED_PROJECT_ROOT=${sharedRoot}`,
    'AIB_ALLOWED_PROJECT_ROOT_CANON=$(CDPATH= cd -- "$AIB_ALLOWED_PROJECT_ROOT" 2>/dev/null && pwd -P) || { echo AIB_ALLOWED_PROJECT_ROOT_MISSING >&2; exit 64; }',
    'case "$AIB_PROJECT_ROOT" in "$AIB_ALLOWED_PROJECT_ROOT_CANON"|"$AIB_ALLOWED_PROJECT_ROOT_CANON"/*) ;; *) echo AIB_PROJECT_ROOT_OUTSIDE_ALLOWED_ROOT >&2; exit 66;; esac',
    'cd -- "$AIB_PROJECT_ROOT" || { echo AIB_PROJECT_ROOT_UNAVAILABLE >&2; exit 65; }',
    `AIB_BUILD_SUBDIRECTORY=${shellQuote(buildSubdirectory)}`,
    'if [ "$AIB_BUILD_SUBDIRECTORY" = "." ]; then AIB_PROJECT_BUILD_ROOT="$AIB_PROJECT_ROOT"; else AIB_PROJECT_BUILD_ROOT="$AIB_PROJECT_ROOT/$AIB_BUILD_SUBDIRECTORY"; fi',
    'AIB_PROJECT_BUILD_ROOT_CANON=$(CDPATH= cd -- "$AIB_PROJECT_BUILD_ROOT" 2>/dev/null && pwd -P) || { echo AIB_PROJECT_BUILD_ROOT_MISSING >&2; exit 67; }',
    'case "$AIB_PROJECT_BUILD_ROOT_CANON" in "$AIB_PROJECT_ROOT"|"$AIB_PROJECT_ROOT"/*) ;; *) echo AIB_PROJECT_BUILD_ROOT_OUTSIDE_PROJECT >&2; exit 66;; esac',
    'AIB_PROJECT_BUILD_ROOT="$AIB_PROJECT_BUILD_ROOT_CANON"',
    '[ -d "$AIB_PROJECT_BUILD_ROOT" ] || { echo AIB_PROJECT_BUILD_ROOT_MISSING >&2; exit 67; }',
    'AIB_PRIVATE_ROOT="${AIB_PRIVATE_ROOT:-$HOME/.aibuilder}"; export AIB_PRIVATE_ROOT AIB_PROJECT_ROOT AIB_PROJECT_BUILD_ROOT; mkdir -p "$AIB_PRIVATE_ROOT/work"',
    'printf "%s\\n" "$AIB_PROJECT_ROOT" > "$AIB_PRIVATE_ROOT/work/project_root"; printf "%s\\n" "$AIB_PROJECT_BUILD_ROOT" > "$AIB_PRIVATE_ROOT/work/build_path"; printf "%s\\n" "$AIB_PROJECT_BUILD_ROOT" > "$AIB_PRIVATE_ROOT/work/proj_path"; printf "%s\\n" "$AIB_PROJECT_ROOT" > "$AIB_PRIVATE_ROOT/work/src_path"',
    `printf 'AIB_BUILD_BACKEND=%s\\nAIB_PROJECT_KIND=%s\\nAIB_BUILD_VARIANT=%s\\n' ${shellQuote(options.backend)} ${shellQuote(options.projectKind)} ${shellQuote(options.variant)}`,
    'for AIB_CFG in ' + audit.map(shellQuote).join(" ") + '; do if [ -f "$AIB_PROJECT_ROOT/$AIB_CFG" ]; then printf "BUILD_CONFIG_PRESERVED=%s\\n" "$AIB_CFG"; fi; done',
    'echo AIB_BUILD_COMMAND_START',
    command,
    "AIB_BUILD_EXIT=$?",
    'echo "AIB_BUILD_COMMAND_EXIT=$AIB_BUILD_EXIT"',
    'exit "$AIB_BUILD_EXIT"',
    "",
  ].join("\n");
}

/**
 * Materialize a generated runner atomically under the proven project directory.
 * Existing user-authored build-apk-*.sh files are never overwritten.
 */
export function buildProjectBuildRunnerMaterializeCommand(options: ProjectBuildRunnerOptions): string {
  const root = shellQuote(options.projectRoot);
  const sharedRoot = shellQuote(options.sharedRoot || DEFAULT_SHARED_ROOT);
  const stem = `build-apk-${projectBuildRunnerSlug(options.projectName)}`;
  const payload = shellQuote(utf8ToBase64(buildProjectBuildRunnerContent(options)));
  return [
    "set -eu",
    `AIB_ROOT=${sharedRoot}`,
    'PROJECT_ROOT=' + root,
    '[ -d "$AIB_ROOT" ] && [ -d "$PROJECT_ROOT" ] || { echo PROJECT_BUILD_RUNNER_ROOT_MISSING >&2; exit 70; }',
    '[ ! -L "$PROJECT_ROOT" ] || { echo PROJECT_BUILD_RUNNER_PROJECT_SYMLINK_DENIED >&2; exit 71; }',
    'AIB_ROOT_CANON=$(CDPATH= cd -- "$AIB_ROOT" && pwd -P) || { echo PROJECT_BUILD_RUNNER_WORKSPACE_MISSING >&2; exit 72; }',
    'PROJECT_CANON=$(CDPATH= cd -- "$PROJECT_ROOT" && pwd -P) || { echo PROJECT_BUILD_RUNNER_PROJECT_UNAVAILABLE >&2; exit 73; }',
    'case "$PROJECT_CANON" in "$AIB_ROOT_CANON"|"$AIB_ROOT_CANON"/*) ;; *) echo PROJECT_BUILD_RUNNER_OUTSIDE_PROJECT_ROOT >&2; exit 74;; esac',
    `BASE=${shellQuote(`${stem}.sh`)}`,
    'DEST="$PROJECT_CANON/$BASE"; I=0',
    'while [ -e "$DEST" ] || [ -L "$DEST" ]; do',
    '  if [ ! -L "$DEST" ] && [ -f "$DEST" ] && head -n 4 "$DEST" | grep -Fqx ' + shellQuote(PROJECT_BUILD_RUNNER_MARKER) + '; then break; fi',
    '  I=$((I+1)); [ "$I" -le 99 ] || { echo PROJECT_BUILD_RUNNER_NAME_COLLISION_LIMIT >&2; exit 75; }',
    `  DEST="$PROJECT_CANON/${stem}-aib-$I.sh"`,
    "done",
    '[ ! -L "$DEST" ] || { echo PROJECT_BUILD_RUNNER_TARGET_SYMLINK_DENIED >&2; exit 76; }',
    'TMP=$(mktemp "$PROJECT_CANON/.aib-build-runner.XXXXXXXX") || { echo PROJECT_BUILD_RUNNER_TEMP_FAILED >&2; exit 77; }',
    `if ! printf '%s' ${payload} | base64 -d > "$TMP"; then rm -f -- "$TMP"; echo PROJECT_BUILD_RUNNER_WRITE_FAILED >&2; exit 78; fi`,
    'head -n 4 "$TMP" | grep -Fqx ' + shellQuote(PROJECT_BUILD_RUNNER_MARKER) + ' || { rm -f -- "$TMP"; echo PROJECT_BUILD_RUNNER_CONTENT_INVALID >&2; exit 79; }',
    'chmod 700 "$TMP" || { rm -f -- "$TMP"; echo PROJECT_BUILD_RUNNER_MODE_FAILED >&2; exit 80; }',
    'mv -f -- "$TMP" "$DEST" || { rm -f -- "$TMP"; echo PROJECT_BUILD_RUNNER_COMMIT_FAILED >&2; exit 81; }',
    'printf "PROJECT_BUILD_SCRIPT=%s\\n" "$DEST"',
  ].join("\n");
}

/** Atomically save and immediately invoke the generated project-local script. */
export function buildProjectBuildRunnerMaterializeAndInvokeCommand(options: ProjectBuildRunnerOptions): string {
  return `${buildProjectBuildRunnerMaterializeCommand(options)}; bash -- "$DEST"`;
}

/** Invoke via bash so shared-storage noexec mounts do not require chmod +x. */
export function buildProjectBuildRunnerInvocation(scriptPath: string): string {
  return `bash -- ${shellQuote(scriptPath)}`;
}

/** Parse only the path marker emitted after an atomic, scoped write. */
export function extractProjectBuildRunnerPath(output: string): string | null {
  const matches = [...String(output || "").matchAll(/^PROJECT_BUILD_SCRIPT=(.+)$/gm)];
  const candidate = matches.at(-1)?.[1]?.trim();
  if (!candidate || !/\/build-apk-[a-z0-9_-]+(?:-aib-\d+)?\.sh$/i.test(candidate)) return null;
  return candidate;
}

export type ProjectBuildRunnerExecutionOptions = Readonly<{
  timeoutMs: number;
  isBuild: true;
  trustedInternal: true;
  backend: ProjectBuildRunnerOptions["backend"];
  workdir: string;
}>;

export type ProjectBuildRunnerExecutionResult = {
  exitCode: number;
  stdout?: string;
  stderr?: string;
  projectBuildScriptPath?: string;
};

/** Materialize and invoke the project-local runner through the selected native executor. */
export async function executeProjectBuildRunner(
  options: ProjectBuildRunnerOptions & { timeoutMs: number },
  execute: (
    command: string,
    executionOptions: ProjectBuildRunnerExecutionOptions,
  ) => Promise<ProjectBuildRunnerExecutionResult>,
): Promise<ProjectBuildRunnerExecutionResult> {
  const result = await execute(
    buildProjectBuildRunnerMaterializeAndInvokeCommand(options),
    {
      timeoutMs: options.timeoutMs,
      isBuild: true,
      trustedInternal: true,
      backend: options.backend,
      workdir: options.projectRoot,
    },
  );
  const output = `${result.stdout || ""}\n${result.stderr || ""}`;
  const scriptPath = extractProjectBuildRunnerPath(output);
  const projectRoot = options.projectRoot.replace(/\/+$/, "");
  if (!scriptPath || !scriptPath.startsWith(`${projectRoot}/build-apk-`)) {
    const failure = "PROJECT_BUILD_RUNNER_PATH_NOT_VERIFIED";
    return {
      ...result,
      exitCode: result.exitCode === 0 ? 70 : result.exitCode,
      stderr: `${result.stderr || ""}\n${failure}`.trim(),
    };
  }
  return { ...result, projectBuildScriptPath: scriptPath };
}
