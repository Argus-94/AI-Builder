export type RuntimeStatusMessagePurpose = "readiness-result" | "preparation-start" | "preparation-result";

export type RuntimeStatusBannerSuppressionInput = Readonly<{
  message: string | null;
  trackedRuntimeMessage: string | null;
  messageSource: "app" | "runtime-status";
  messagePurpose: RuntimeStatusMessagePurpose | null;
  selectedReadinessStatus: "ready" | "missing" | "error" | null;
  /** Exact localized readiness cause currently rendered in the selected Runtime card. */
  selectedCardCause: string | null;
  /** Exact localized prepareBlocked(...) result for selectedCardCause; never a fuzzy prefix. */
  expectedPreparationResult: string | null;
}>;

/**
 * Hide only a tracked Runtime-result banner whose cause is already visible in the
 * selected card. Composite suppression is limited to the exact localized wrapper
 * generated by prepareBlocked; arbitrary messages containing the cause stay visible.
 */
export function shouldHideDuplicateRuntimeStatusBanner(input: RuntimeStatusBannerSuppressionInput): boolean {
  const {
    message,
    trackedRuntimeMessage,
    messageSource,
    messagePurpose,
    selectedReadinessStatus,
    selectedCardCause,
    expectedPreparationResult,
  } = input;

  if (
    messageSource !== "runtime-status" ||
    typeof message !== "string" ||
    message.length === 0 ||
    message !== trackedRuntimeMessage ||
    selectedReadinessStatus === null ||
    typeof selectedCardCause !== "string" ||
    selectedCardCause.length === 0 ||
    (messagePurpose !== "readiness-result" && messagePurpose !== "preparation-result")
  ) return false;

  if (message === selectedCardCause) return true;

  if (selectedReadinessStatus !== "error") return false;

  return messagePurpose === "preparation-result" &&
    typeof expectedPreparationResult === "string" &&
    expectedPreparationResult !== selectedCardCause &&
    message === expectedPreparationResult;
}
