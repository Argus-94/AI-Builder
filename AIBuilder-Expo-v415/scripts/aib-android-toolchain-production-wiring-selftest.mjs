#!/usr/bin/env node
import assert from "node:assert/strict";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(fileURLToPath(new URL("..", import.meta.url)));
const read = (relative) => fs.readFileSync(path.join(root, relative), "utf8");
const buildLoop = read("core/workspace/AgenticBuildLoop.ts");
const autonomousLoop = read("lib/autonomous-device-loop.ts");
const build = read("lib/build-loop.ts");
const runtime = read("core/RuntimeFacade.ts");
const agentManager = read("core/agent/AgentManager.ts");
const appLoop = read("core/device/DeviceAppLoop.ts");
const deviceGate = read("core/enhancements/device/PolicyGatedDeviceAgentBridge.ts");
const policy = read("core/enhancements/device/DevicePolicy.ts");
const adapter = read("core/enhancements/toolchain/AndroidToolchainProductionAdapter.ts");
const adbPairing = read("lib/adb-pairing.ts");
const chatUi = read("app/index.tsx");

assert.match(buildLoop, /runtime\.runAICodingAgent\(request\.containerId/);
assert.match(buildLoop, /runAutonomousDeviceDevelopmentLoop\(/);
assert.match(autonomousLoop, /runAssembleDebug\(options\.projectPath/);
assert.match(autonomousLoop, /options\.repair\(buildFixPrompt\(/);
assert.match(autonomousLoop, /runtime\.runDeviceAutomationAsAgent\(/);
assert.match(build, /signApkV123\(projectPath, rawApk\)/);
assert.match(build, /SIGNED_V1_V2_V3_OK/);
assert.match(build, /const ok = fullySigned/);
assert.match(appLoop, /bridge\.install\(options\.apkPath\)/);
assert.match(appLoop, /detectPackageName\(bridge, options\.apkPath\)/);
assert.match(runtime, /tool:\s*"device\.automation_loop",\s*capability:\s*"adb"/);
assert.match(runtime, /new PolicyGatedDeviceAgentBridge\(this\.devicePolicy/);
assert.match(agentManager, /if \(request\.tool === "device\.automation_loop"\)/);
assert.match(agentManager, /allowedCapabilities\.includes\("adb"\)/);
assert.match(deviceGate, /policy\.run\(`adb\.device\.\$\{operation\}`/);
assert.match(deviceGate, /install\(path: string\): Promise<DeviceCommandResult>.*this\.run\("install"/);
assert.match(policy, /if \(!this\.grants\.has\(required\)\)/);
assert.match(policy, /grantByUser\(capability: DeviceCapability\)/);
assert.match(runtime, /runAndroidToolchainCoordinator\(adapter/);
assert.match(runtime, /maxRepairAttempts: 0/);
assert.doesNotMatch(adapter, /repair\s*:/, "production adapter must not expose an automatic repair callback without a safe host rollback gate");
const coordinator = read("core/enhancements/toolchain/AndroidToolchainCoordinator.ts");
assert.match(coordinator, /AUTOMATIC_REPAIR_UNAVAILABLE_SAFE_HOST/);
assert.match(coordinator, /isolated worktree\/temp-patch staging/);
assert.match(coordinator, /atomic compare-and-swap apply\/revert/);
assert.match(runtime, /name: "android\.toolchain\.run"/);
assert.match(runtime, /offlineToolchainSessions\.set\(agent\.id/);
assert.match(runtime, /confirmDeviceInstall/);
assert.match(runtime, /offlineBuildConfigWriteBlocked/);
assert.match(runtime, /"package\.json", "package-lock\.json", "pnpm-lock\.yaml"/);
assert.match(runtime, /"app\.json", "ai_builder_android_identity\.json"/);
assert.match(runtime, /segment === "buildsrc" \|\| segment === "build-logic"/);
assert.ok(runtime.includes("\\.gradle(?:\\.kts)?$"));
assert.match(runtime, /"gradle-wrapper\.jar", "gradlew", "gradlew\.bat"/);
assert.match(agentManager, /if \(request\.tool === "android\.toolchain\.run"\)/);
assert.match(agentManager, /beforeFileWrite\(agent, `\$\{projectRoot/);
assert.match(adapter, /source\.package\.json/);
assert.match(adapter, /source\.app\.config\.ts/);
assert.match(build, /AIB_GRADLE_EXTRA_FLAGS=--offline/);
assert.match(build, /GRADLE_DISTRIBUTION_NOT_CACHED_OFFLINE/);
assert.match(build, /buildCommand\(root, "", false, false, false\)/);
assert.match(build, /androidBuildEnvironment\(root, false, false\)/);
assert.match(build, /LOCAL_PROPERTIES_WRITE_SKIPPED/);
assert.match(build, /AIB_SDK_LICENSES_NOT_ACCEPTED/);
assert.match(adbPairing, /device\.serial === hp && device\.state === "device"/);
assert.match(adbPairing, /if \(connectAccepted && online\)/);
assert.match(chatUi, /testID="offline-agent-toolchain"/);
assert.match(chatUi, /testID="offline-agent-install"/);
assert.match(chatUi, /allowAndroidToolchain,/);
assert.match(chatUi, /confirmOfflineDeviceInstall/);
assert.match(chatUi, /devicePolicy\.isGranted\("device\.adb"\)/);

console.log("AIB_ANDROID_TOOLCHAIN_PRODUCTION_WIRING_SELFTEST_OK coordinator=production-adapter offline-agent=dedicated-capability+checkpoint build=cached-offline identity=immutable install=explicit-consent adb=online-verified execution=not_run");
