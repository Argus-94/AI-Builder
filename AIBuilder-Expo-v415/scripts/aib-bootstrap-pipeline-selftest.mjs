#!/usr/bin/env node
import assert from "node:assert/strict";
import fs from "node:fs";
import path from "path";
import { fileURLToPath } from "node:url";
const root = path.resolve(fileURLToPath(new URL("..", import.meta.url)));
const pipe = fs.readFileSync(path.join(root, "core/runtime/BootstrapPipeline.ts"), "utf8");
assert.match(pipe, /termux-ready/);
assert.match(pipe, /environment-image/);
assert.match(pipe, /fingerprint/);
assert.match(pipe, /async run\(/);
assert.match(pipe, /reset/);
const runner = fs.readFileSync(path.join(root, "lib/bootstrap-stage-runner.ts"), "utf8");
const installer = fs.readFileSync(path.join(root, "lib/termux-bootstrap-install.ts"), "utf8");
const aptInstall = fs.readFileSync(path.join(root, "lib/termux-apt-install.ts"), "utf8");
assert.match(runner, /createDefaultBootstrapRunner/);
const rootfsState = fs.readFileSync(path.join(root, "lib/proot-distro-state.ts"), "utf8");
const stageCore = fs.readFileSync(path.join(root, "lib/bootstrap-stage-core.ts"), "utf8");
assert.match(stageCore, /rootfsDistroForBackend\(selectedBackend\)/);
assert.match(stageCore, /routeRuntimeCommand\(selectedBackend, "proot-distro"\)/);
assert.match(stageCore, /buildProotDistroRootfsInstallCommand\(distro\)/);
assert.match(stageCore, /buildProotDistroRootfsCheckCommand\(distro\)/);
assert.match(installer, /from "\.\/proot-distro-state\.ts"/);
assert.match(rootfsState, /proot-distro install \$\{alias\}/);
assert.match(rootfsState, /AIB_PROBE_ID:%s/);
assert.match(installer, /wrapTermuxAptInstallWithUpdate/);
assert.match(installer, /apt-get install -y openjdk-17 unzip git wget curl/);
assert.match(aptInstall, /cat "\$AIB_UP_LOG"/);
assert.match(aptInstall, /cat "\$AIB_UP_STDERR" >&2/);
const facade = fs.readFileSync(path.join(root, "core/RuntimeFacade.ts"), "utf8");
assert.match(facade, /bootstrapRun/);
assert.match(facade, /bindBootstrapRunner/);
const ui = fs.readFileSync(path.join(root, "app/runtime.tsx"), "utf8");
assert.match(ui, /const onBootstrapContinue = useCallback\(/);
assert.match(ui, /Продолжение bootstrap…|Resuming bootstrap…/);
const rf = fs.readFileSync(path.join(root, "lib/runtime-facade.ts"), "utf8");
assert.match(rf, /bindBootstrapRunner/);
const hostEnvironment = fs.readFileSync(path.join(root, "core/environment/AIBuilderTermuxEnvironment.ts"), "utf8");
assert.match(hostEnvironment, /hostTermux: true/);
assert.match(hostEnvironment, /backend: "termux"/);
const userspace = fs.readFileSync(path.join(root, "core/runtime/AibUserspaceRuntime.ts"), "utf8");
assert.match(userspace, /prootProfileProvider/);
console.log("AIB_BOOTSTRAP_PIPELINE_SELFTEST_OK");
