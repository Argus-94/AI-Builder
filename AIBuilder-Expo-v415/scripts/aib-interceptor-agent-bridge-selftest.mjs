import assert from "node:assert/strict";
import { loadTs, memoryAdapter, request } from "./aib-interceptor-test-helper.mjs";
const { InterceptorAgentBridge } = loadTs("core/enhancements/interceptor/InterceptorAgentBridge.ts");
const { InterceptorCapture } = loadTs("core/enhancements/interceptor/InterceptorCapture.ts");
const { InterceptorEngine } = loadTs("core/enhancements/interceptor/InterceptorEngine.ts");
const { InterceptorPolicy } = loadTs("core/enhancements/interceptor/InterceptorPolicy.ts");
const { InterceptorReplay } = loadTs("core/enhancements/interceptor/InterceptorReplay.ts");
const { InterceptorRules } = loadTs("core/enhancements/interceptor/InterceptorRules.ts");
const { InterceptorStore } = loadTs("core/enhancements/interceptor/InterceptorStore.ts");
const events = []; const policy = new InterceptorPolicy((event) => events.push(event)); await policy.confirmUserEnable(true);
const capture = new InterceptorCapture(); const item = capture.record({ request: request("agent-1", "https://1.1.1.1/request"), response: { status: 200, headers: { "content-type": "application/json" }, body: '{"ok":true}' }, timing: { start: 1, end: 2, totalMs: 1 } });
let handler; const adapter = { async start(options) { handler = options.onRequest; return { address: "127.0.0.1", port: options.port, verified: true }; }, async stop() {} };
const store = new InterceptorStore(memoryAdapter()); const engine = new InterceptorEngine(store, policy, capture, new InterceptorRules(), adapter);
const replay = new InterceptorReplay(policy, async () => new Response('{"ok":false}', { status: 201 }));
const bridge = new InterceptorAgentBridge(engine, store, capture, replay, (event) => events.push(event));
await assert.rejects(() => bridge.executeNaturalLanguage("Покажи последние 10 запросов", false), /CAPABILITY_REQUIRED/);
const added = await bridge.executeNaturalLanguage("Заблокируй все запросы к google-analytics", true);
assert.equal(added.created, true);
assert.equal((await store.listRules()).length, 1);
const last = await bridge.executeNaturalLanguage("Покажи последние 10 запросов", true);
assert.equal(last.length, 1);
const detail = await bridge.execute({ action: "detail", id: item.id }, true);
assert.equal(detail.request.url, item.request.url);
const replayResult = await bridge.execute({ action: "replay", id: item.id }, true);
assert.equal(replayResult.response.status, 201);
await bridge.execute({ action: "rule-toggle", id: added.id, enabled: false }, true);
assert.equal((await store.listRules())[0].enabled, false);
await bridge.execute({ action: "rule-delete", id: added.id }, true);
assert.equal((await store.listRules()).length, 0);
await bridge.executeNaturalLanguage("Отключи все правила и выключи перехват", true);
assert.ok(events.some((event) => event.source === "agent" && event.outcome === "allowed"));
console.log("aib-interceptor-agent-bridge-selftest: PASS");
