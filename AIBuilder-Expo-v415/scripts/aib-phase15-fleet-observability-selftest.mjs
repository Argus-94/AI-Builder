for (const token of ['getFleetObservability','listFleetIncidents','acknowledgeFleetIncident','incident-','failureRate','SUMMARY.txt']) if (!src.includes(token)) throw new Error(`CONTRACT:${token}`);
const ui = fs.readFileSync(path.join(root,'app/runtime.tsx'),'utf8');
const runtimeI18n = fs.readFileSync(path.join(root,'lib/runtime-i18n.ts'),'utf8');
