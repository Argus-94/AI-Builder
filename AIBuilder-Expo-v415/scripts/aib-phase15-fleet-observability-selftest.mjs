if (!hook.includes('runAIFleetObservability')) throw new Error('HOOK_MISSING');
const pkg = JSON.parse(fs.readFileSync(path.join(root,'package.json'),'utf8'));
pkg.scripts ||= {};
if (pkg.scripts['test:phase15-fleet-observability'] !== 'node scripts/aib-phase15-fleet-observability-selftest.mjs') throw new Error('SCRIPT_MISSING');
