import fs from 'node:fs';
import path from 'node:path';
const root = process.cwd();
const read = (f) => fs.readFileSync(path.join(root, f), 'utf8');
const runner = read('app/script-runner.tsx');
const consoleCtx = read('components/TermuxConsoleContext.tsx');
const backend = read('lib/package-backend.ts');
const routing = read('lib/package-command-routing.ts');
const packages = read('lib/compile-packages.ts');
const ubuntu = read('lib/ubuntu-distro.ts');
if (/runShellCommand\(/.test(runner)) throw new Error('AIB_V140_RAW_SCRIPTRUNNER_EXECUTOR');
if (/runShellCommand\(/.test(consoleCtx)) throw new Error('AIB_V140_RAW_CONSOLE_EXECUTOR');
if (!/executeGuardedTermuxCommand/.test(runner) || !/executeGuardedTermuxCommand/.test(consoleCtx)) throw new Error('AIB_V140_CENTRAL_EXECUTOR_MISSING');
if (!/isPackageSupportedOnBackend/.test(backend) || !/packageId === "android-ndk"/.test(routing)) throw new Error('AIB_V140_NDK_LINUX_GUARD_MISSING');
if (!/__SDKMANAGER__/.test(routing)) throw new Error('AIB_V140_SDKMANAGER_MAPPING_MISSING');
if (!/withForegroundTask\(\"bootstrap\", \"Ubuntu rootfs\"/.test(ubuntu)) throw new Error('AIB_V140_UBUNTU_FOREGROUND_SIGNATURE');
if (/PLATFORM34_FAIL[\s\S]*exit 1`,[\s\S]*PLATFORM34_OK/.test(packages)) throw new Error('AIB_V140_PLATFORM34_DEAD_CODE');
if (/PLATFORM35_FAIL[\s\S]*exit 1`,[\s\S]*PLATFORM35_OK/.test(packages)) throw new Error('AIB_V140_PLATFORM35_DEAD_CODE');
console.log('AIB_V140_REMAINING_PATHS_SELFTEST_OK');
