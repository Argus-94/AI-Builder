export type TranslationKey = keyof typeof translations.uk;

export function t(lang: AppLanguage, key: TranslationKey, params?: Record<string, string | number>): string {
  const table = translations[lang];
  const value = table[key] ?? translations.uk[key];
  if (typeof value !== "string") return String(key);
  if (!params) return value;
  return value.replace(/\{(\w+)\}/g, (_, k) =>
    params[k] !== undefined ? String(params[k]) : `{${k}}`
  );
}

