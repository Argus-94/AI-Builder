#!/usr/bin/env node
import assert from "node:assert/strict";
import fs from "node:fs";
import path from "path";
import { fileURLToPath } from "node:url";
const root = path.resolve(fileURLToPath(new URL("..", import.meta.url)));
const pipe = fs.readFileSync(path.join(root, "core/runtime/BootstrapPipeline.ts"), "utf8");
assert.match(pipe, /termux-ready/);
assert.match(pipe, /debian-image/);
assert.match(pipe, /fingerprint/);
assert.match(pipe, /async run\(/);
assert.match(pipe, /reset/);
const runner = fs.readFileSync(path.join(root, "lib/bootstrap-stage-runner.ts"), "utf8");
assert.match(runner, /createDefaultBootstrapRunner/);
assert.match(runner, /proot-distro install debian/);
const facade = fs.readFileSync(path.join(root, "core/RuntimeFacade.ts"), "utf8");
assert.match(facade, /bootstrapRun/);
assert.match(facade, /bindBootstrapRunner/);
const ui = fs.readFileSync(path.join(root, "app/runtime.tsx"), "utf8");
assert.match(ui, /onBootstrapContinue/);
assert.match(ui, /Bootstrap среды|Environment bootstrap/);
const rf = fs.readFileSync(path.join(root, "lib/runtime-facade.ts"), "utf8");
assert.match(rf, /bindBootstrapRunner/);
console.log("AIB_BOOTSTRAP_PIPELINE_SELFTEST_OK");
